import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

/*
 * Wrangler only discovers a Pages configuration file in the directory it is
 * run from, and `wrangler pages dev` always serves Functions from
 * `<cwd>/functions`. The tracked config lives in `admin/` so it stays next to
 * the Pages project, but local development has to run from the repo root.
 *
 * This script writes the root `wrangler.toml` that `npm run dev:cms` uses. It
 * is git-ignored on purpose: committing it would make Cloudflare treat it as
 * the source of truth for the Pages project, and the binding ids are still
 * Phase 1 placeholders.
 */

const MARKER = '# Generated by scripts/prepare-local-wrangler.mjs'
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = join(root, 'admin', 'wrangler.toml')
const targetPath = join(root, 'wrangler.toml')

if (existsSync(targetPath)) {
  const existing = readFileSync(targetPath, 'utf8')
  if (!existing.startsWith(MARKER)) {
    console.log('Root wrangler.toml is not generated; leaving it untouched.')
    process.exit(0)
  }
}

let config = readFileSync(sourcePath, 'utf8')
config = config
  .replace(/^pages_build_output_dir\s*=\s*"dist"$/m, 'pages_build_output_dir = "admin/dist"')
  .replace(/^migrations_dir\s*=\s*"\.\.\/migrations"$/m, 'migrations_dir = "./migrations"')

if (!config.includes('pages_build_output_dir = "admin/dist"')) {
  throw new Error('Could not rewrite pages_build_output_dir in admin/wrangler.toml')
}

writeFileSync(
  targetPath,
  `${MARKER}
# Source: admin/wrangler.toml. Local development only - do not commit (git-ignored).
# Regenerated automatically by \`npm run dev:cms\`.

${config}`,
)
